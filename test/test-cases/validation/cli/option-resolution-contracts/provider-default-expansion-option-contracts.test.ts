import { describe,expect,test } from 'bun:test'
import { buildOptsFromFlags } from '~/cli/options/option-resolution/build-options-from-flags'

describe('option resolution contracts', () => {

  test('--all-llm expands OpenAI, Anthropic, Gemini and Grok to their supported models', () => {
      const opts = buildOptsFromFlags({ 'all-llm': true })

      expect(opts.openaiModels).toEqual(['gpt-6.1-sol', 'gpt-6-luna'])
      expect(opts.openaiModels).not.toContain('gpt-5.6')
      expect(opts.anthropicModels).toEqual(['claude-opus-5-5', 'claude-sonnet-5-5', 'claude-haiku-5-5'])
      expect(opts.anthropicModels).not.toContain('claude-fable-5')
      expect(opts.anthropicModels).not.toContain('claude-mythos-5')
      expect(opts.geminiModels).toEqual(['gemini-4-argon', 'gemini-3.8-flash'])
      expect(opts.geminiModels).not.toContain('gemini-3.6-flash')
      expect(opts.geminiModels).not.toContain('gemini-3.5-flash')
      expect(opts.geminiModels).not.toContain('gemini-3.1-flash-lite')
      expect(opts.geminiModels).not.toContain('gemini-3-flash-preview')
      expect(opts.grokModels).toEqual(['grok-4.7'])
      expect(opts.grokModels).not.toContain('grok-4.5')
    })

  test('priority OCR model additions are available without changing provider defaults', () => {
      const openaiSolWriteOpts = buildOptsFromFlags({ openai: 'gpt-6.1-sol' })
      const openaiGpt55WriteOpts = buildOptsFromFlags({ openai: 'gpt-6.1-sol' })
      const mistralOcr4Opts = buildOptsFromFlags({ 'mistral-ocr': 'mistral-ocr-4-1' })
      const openaiSolOcrOpts = buildOptsFromFlags({ 'openai-ocr': 'gpt-6.1-sol' })
      const openaiOcrOpts = buildOptsFromFlags({ 'openai-ocr': 'gpt-6-luna' })
      const openaiGpt55OcrOpts = buildOptsFromFlags({ 'openai-ocr': 'gpt-6.1-sol' })
      const grokWriteOpts = buildOptsFromFlags({ grok: 'grok-4.7' })
      const grokOcrOpts = buildOptsFromFlags({ 'grok-ocr': 'grok-4.7' })
      const grok46OcrOpts = buildOptsFromFlags({ 'grok-ocr': 'grok-4.7' })
      const gemini37OcrOpts = buildOptsFromFlags({ 'gemini-ocr': 'gemini-3.8-flash' })
      const writeOpts = buildOptsFromFlags({ anthropic: 'claude-sonnet-5-5' })
      const anthropicSonnet5WriteOpts = buildOptsFromFlags({ anthropic: 'claude-sonnet-5-5' })
      const anthropicFableOcrOpts = buildOptsFromFlags({ 'anthropic-ocr': 'claude-fable-5' })
      const anthropicOpusOcrOpts = buildOptsFromFlags({ 'anthropic-ocr': 'claude-opus-5-5' })
      const anthropicSonnet5OcrOpts = buildOptsFromFlags({ 'anthropic-ocr': 'claude-sonnet-5-5' })
      const anthropicSonnet46OcrOpts = buildOptsFromFlags({ 'anthropic-ocr': 'claude-sonnet-5-5' })
      const anthropicHaikuOcrOpts = buildOptsFromFlags({ 'anthropic-ocr': 'claude-sonnet-5-5' })

      // Fully removed OpenAI models reject for both write and OCR before any target is built.
      for (const model of ['gpt-6-astra', 'gpt-5.6-terra']) {
        expect(() => buildOptsFromFlags({ openai: model })).toThrow(`Invalid model "${model}" for --llm openai[=model]. Allowed values: gpt-6.1-sol, gpt-6-luna`)
        expect(() => buildOptsFromFlags({ 'openai-ocr': model })).toThrow(`Invalid model "${model}" for --provider/--ocr openai[=model]. Allowed values: gpt-6.1-sol, gpt-6-luna`)
      }
      expect(openaiSolWriteOpts.openaiModels?.[0]).toBe('gpt-6.1-sol')
      expect(openaiGpt55WriteOpts.openaiModels?.[0]).toBe('gpt-6.1-sol')
      expect(mistralOcr4Opts.mistralOcrModels?.[0]).toBe('mistral-ocr-4-1')
      expect(openaiSolOcrOpts.openaiOcrModels?.[0]).toBe('gpt-6.1-sol')
      expect(openaiOcrOpts.openaiOcrModels?.[0]).toBe('gpt-6-luna')
      expect(openaiOcrOpts.openaiOcrModels).toEqual(['gpt-6-luna'])
      // Write-only Gemini models and retired OCR selectors reject before any OCR target is built.
      expect(() => buildOptsFromFlags({ 'grok-ocr': 'grok-4.5' })).toThrow('Invalid model "grok-4.5" for --provider/--ocr grok[=model]. Allowed values: grok-4.7')
      for (const model of ['gemini-3.5-flash', 'gemini-3.6-flash', 'gemini-4-argon']) expect(() => buildOptsFromFlags({ 'gemini-ocr': model })).toThrow(`Invalid model "${model}" for --provider/--ocr gemini[=model]. Allowed values: gemini-3.8-flash`)
      expect(openaiGpt55OcrOpts.openaiOcrModels?.[0]).toBe('gpt-6.1-sol')
      expect(grokWriteOpts.grokModels?.[0]).toBe('grok-4.7')
      expect(grokOcrOpts.grokOcrModels).toEqual(['grok-4.7'])
      expect(grok46OcrOpts.grokOcrModels?.[0]).toBe('grok-4.7')
      expect(gemini37OcrOpts.geminiOcrModels?.[0]).toBe('gemini-3.8-flash')
      expect(writeOpts.anthropicModels?.[0]).toBe('claude-sonnet-5-5')
      expect(() => buildOptsFromFlags({ anthropic: 'claude-fable-5-1' })).toThrow('Invalid model "claude-fable-5-1" for --llm anthropic[=model]. Allowed values: claude-opus-5-5, claude-sonnet-5-5, claude-haiku-5-5')
      expect(() => buildOptsFromFlags({ 'anthropic-ocr': 'claude-fable-5-1' })).toThrow('Invalid model "claude-fable-5-1" for --provider/--ocr anthropic[=model]. Allowed values: claude-opus-5-5, claude-sonnet-5-5, claude-haiku-5-5, claude-fable-5')
      expect(() => buildOptsFromFlags({ grok: 'grok-4.5' })).toThrow('Invalid model "grok-4.5" for --llm grok[=model]. Allowed values: grok-4.7')
      expect(() => buildOptsFromFlags({ anthropic: 'claude-fable-5' })).toThrow('Invalid model "claude-fable-5" for --llm anthropic[=model]. Allowed values: claude-opus-5-5, claude-sonnet-5-5, claude-haiku-5-5')
      expect(anthropicSonnet5WriteOpts.anthropicModels?.[0]).toBe('claude-sonnet-5-5')
      expect(anthropicFableOcrOpts.anthropicOcrModels?.[0]).toBe('claude-fable-5')
      expect(anthropicOpusOcrOpts.anthropicOcrModels?.[0]).toBe('claude-opus-5-5')
      expect(anthropicOpusOcrOpts.anthropicOcrModels).toEqual(['claude-opus-5-5'])
      expect(anthropicSonnet5OcrOpts.anthropicOcrModels?.[0]).toBe('claude-sonnet-5-5')
      expect(anthropicSonnet46OcrOpts.anthropicOcrModels?.[0]).toBe('claude-sonnet-5-5')
      expect(anthropicHaikuOcrOpts.anthropicOcrModels?.[0]).toBe('claude-sonnet-5-5')
      expect(() => buildOptsFromFlags({ openai: 'gpt-5.6' })).toThrow()
      expect(() => buildOptsFromFlags({ anthropic: 'claude-mythos-5' })).toThrow()
    })
})
